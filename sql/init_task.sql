-- =============================================================================
-- 极简任务系统 - 任务表建表与预置数据
--
-- 用途：
--   1) 换一台机器部署时，执行本脚本即可得到可运行的空库 + 演示数据（环节四）；
--   2) 预置 30 条数据用于验证分页——dev 每页 5 条 = 6 页，test 每页 3 条 = 10 页，
--      prod 每页 10 条 = 3 页，切换 profile 时翻页效果肉眼可见地不同。
--
-- 执行方式（PowerShell / cmd，二选一）：
--   mysql -uroot -p < sql/init_task.sql
--   source D:/devops/task-servlet-demo/sql/init_task.sql     -- 已在 mysql 客户端里时
--
-- 幂等性：建表用 IF NOT EXISTS，数据用 INSERT IGNORE + 显式主键，
--   重复执行不会报错也不会产生重复数据。要恢复初始状态先执行：
--   TRUNCATE TABLE t_task; 然后重新跑本脚本。
-- =============================================================================

CREATE DATABASE IF NOT EXISTS taskmaster
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_general_ci;

USE taskmaster;

-- -----------------------------------------------------------------------------
-- 任务表
-- 字段与实体 cn.edu.mju.band.entity.Task 一一对应（下划线 <-> 驼峰，由
-- mybatis-plus.configuration.map-underscore-to-camel-case 自动转换）。
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS t_task (
    id          INT          NOT NULL AUTO_INCREMENT           COMMENT '主键，自增',
    title       VARCHAR(50)  NOT NULL                          COMMENT '任务标题，与 TaskForm 的 @Size(max=50) 对齐',
    status      TINYINT      NOT NULL DEFAULT 0                COMMENT '状态：0=待办 1=进行中 2=已完成',
    priority    TINYINT      NOT NULL DEFAULT 1                COMMENT '优先级：1=低 2=中 3=高',
    due_date    DATE         NULL                              COMMENT '截止日期，可为空',
    create_date DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间，由数据库生成，业务代码不写',
    PRIMARY KEY (id),
    -- 列表页默认按 status 过滤，加索引；create_date 用于"最近创建"类查询
    KEY idx_status (status),
    KEY idx_create_date (create_date)
    -- 注意：title 不加普通索引。列表页用的是 LIKE '%关键字%'，
    -- B+Tree 的前缀匹配对左侧通配符无效，加了也不会走索引，纯属浪费写入性能。
    -- 真需要全文检索时应上 FULLTEXT 或 Elasticsearch。
) ENGINE = InnoDB
  DEFAULT CHARSET = utf8mb4
  COLLATE = utf8mb4_general_ci
  COMMENT = '任务表';

